/**
 * **材料の期限が、実測を下回らないこと**（#573）。
 *
 * **5 秒では足りなかった。** **この機械で測ったら、PR 2 本で 5627 ms**
 * ——**取得は成功しているのに、毎回打ち切られていた。** **利用者には全 PR が
 * 「材料がありません」に見え**、**MVP の 3 機能のうち 1 つが画面から使えなかった。**
 *
 * **これがこの PR の主修正である。** **足したもの（記録・画面の言い分け）には
 * 変異を打ったのに、直したものには打っていなかった**（#577 のレビュー）
 * ——**`5_000` に戻しても全部緑だった。**
 *
 * **`AGENTS.md` §4 の「数えるのは書く前」**は、**守りたいものを先に並べること**でもある。
 * **並べていれば、期限が 1 番目に来た。**
 *
 * **上限は置かない。** **長すぎて困るのは画面が待つことだが、そちらは
 * `collectChanges` が合図で縮退させる**——**ここで守りたいのは下限だけ**である。
 */

import { describe, expect, it } from "vitest";
import { CHANGES_DEADLINE_MS } from "./auth";

/**
 * **実測（2026-09-02、PR 2 本）。** **1 本あたり 3 往復**（詳細・ファイル・CI）で、
 * **本数ぶん増える**——**およそ 1 本 2.8 秒**である。
 */
const MEASURED_MS = 5_627;

describe("材料の期限", () => {
  it("実測を下回らない", () => {
    // **下回ると、取得が成功していても毎回打ち切る**——**これがこの Issue である**
    expect(CHANGES_DEADLINE_MS).toBeGreaterThan(MEASURED_MS);
  });

  it("実測に余裕を足してある（本数が増える）", () => {
    // **2 本で 5.6 秒**なので、**倍でも 3 本ぶん**しかない
    // ——**余裕が無いと、PR が 1 本増えた日に戻る**
    expect(CHANGES_DEADLINE_MS).toBeGreaterThanOrEqual(MEASURED_MS * 3);
  });
});
