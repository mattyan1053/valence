/**
 * **その盤面を、いつ取ったか**（#664）。
 *
 * **「新しい」とも「古い」とも言わない。** **取れた時刻を出せば、読む人が決められる**
 * ——**#639 が「遅れすぎ」と言わずに「35 遅れ」と出したのと同じ線**である。
 *
 * **言い切ると、開いたまま置かれた盤面が「最新」を名乗る**——**#664 が消しに来た
 * 状態そのもの**である（**盤面は開いた瞬間のスナップショット**）。
 *
 * **判定はしない**（`ballNote` と同じ）——**時刻を画面の語彙に当てるだけ**である。
 */

/**
 * **UTC で出す。**
 *
 * **見る人の時間帯を、サーバは知らない**（**盤面はサーバで描いている**）——
 * **推量した時間帯で出すと、1 時間ずれた時刻を「取った時刻」として見せることになる。**
 * **`Z` を付けて、どの時間帯かを言い切る**ほうが、**読む人が自分の時計と
 * 突き合わせられる。**
 *
 * **秒までにする。** **ミリ秒は、人が突き合わせるのに要らない。**
 */
export function fetchedAtNote(at: Date): string {
  return `この盤面は ${at.toISOString().replace(/\.\d{3}Z$/, "Z")} 時点のものです`;
}
